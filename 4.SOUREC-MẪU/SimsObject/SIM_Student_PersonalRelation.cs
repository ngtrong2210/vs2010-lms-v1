	public partial class SIM_Student_PersonalRelation
	{	
		
		#region Methods	
		
        public bool GetMore(long? personalRelationID, long? studentID)
        {
            if (!bolIsExistIData)
                objIData = DCore.Data.CreateData();
            try
            {
                objIData.CreateNewStoredProcedure("SIM_Student_PersonalRelation_GetMore");
                objIData.AddParameter(P_PersonalRelationID, personalRelationID);
                objIData.AddParameter(P_StudentID,studentID);
                IDataReader reader = objIData.ExecStoreToDataReader();
                if (reader.Read())
                {
                    if (Parse(reader))
                    {
                        reader.Close();
                        return true;
                    }
                }
                reader.Close();
                return false;
            }
            catch (Exception objEx)
            {
                if (bolIsExistIData)
                    this.RollBackTransaction();
                new SystemError(SystemConfig.ConnectionString, "Lỗi nạp thông tin SIM_Student_PersonalRelation", objEx);
                this.objErrorException = objEx;
                return false;
            }
            finally
            {
                if (!bolIsExistIData)
                    objIData.Disconnect();
            }
        }		
		#endregion
	
	}
}
