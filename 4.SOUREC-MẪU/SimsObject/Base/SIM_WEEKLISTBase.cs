		/// <returns>true ? Có : False ? Không</returns>
		public bool Parse(IDataReader reader)
		{
			try 
			{
				for (int i = 0; i < reader.FieldCount; i++)
				{
					if (reader.GetName(i).ToUpper().Equals(C_WeekID.ToUpper()) && !Convert.IsDBNull(reader[C_WeekID])) this.intWeekID = Convert.ToInt32(reader[C_WeekID]);
 				}
				return true;
			}
