using System;
using System.Data;
using System.Collections.Generic;
using System.Linq;

namespace LmsObject
{
    /// <summary>
    /// Phần mở rộng nghiệp vụ của SIM_Timetable. Generator không ghi đè file này.
    /// </summary>
    public partial class SIM_Timetable
    {
        #region Custom Data Access Methods

        /// <summary>
        /// Lấy thời khóa biểu theo lớp
        /// </summary>
        public DataTable GetByClass(long classID)
        {
            if (!bolIsExistIData) objIData = DCore.Data.CreateData();
            try
            {
                objIData.CreateNewStoredProcedure(StoreSearch);
                objIData.AddParameter("@ClassID", classID);
                return objIData.ExecStoreToDataTable();
            }
            catch (Exception objEx)
            {
                this.objErrorException = objEx;
                return null;
            }
            finally { if (!bolIsExistIData) objIData.Disconnect(); }
        }

        /// <summary>
        /// Lấy thời khóa biểu theo giáo viên
        /// </summary>
        public DataTable GetByTeacher(long teacherID)
        {
            if (!bolIsExistIData) objIData = DCore.Data.CreateData();
            try
            {
                objIData.CreateNewStoredProcedure("SIM_Timetable_GetByTeacher");
                objIData.AddParameter("@TeacherID", teacherID);
                return objIData.ExecStoreToDataTable();
            }
            catch (Exception objEx)
            {
                this.objErrorException = objEx;
                return null;
            }
            finally { if (!bolIsExistIData) objIData.Disconnect(); }
        }

        #endregion
    }
}
