using System;
using System.Data;
using System.Collections.Generic;
using System.Linq;

namespace LmsObject
{
    /// <summary>
    /// Phần mở rộng nghiệp vụ của SIM_Subject. Generator không ghi đè file này.
    /// </summary>
    public partial class SIM_Subject
    {
        #region Custom Data Access Methods

        /// <summary>
        /// Lấy danh sách môn học theo khoa
        /// </summary>
        public DataTable GetByFaculty(long facultyID)
        {
            if (!bolIsExistIData) objIData = DCore.Data.CreateData();
            try
            {
                objIData.CreateNewStoredProcedure(StoreSearch);
                objIData.AddParameter("@FacultyID", facultyID);
                return objIData.ExecStoreToDataTable();
            }
            catch (Exception objEx)
            {
                this.objErrorException = objEx;
                return null;
            }
            finally { if (!bolIsExistIData) objIData.Disconnect(); }
        }

        /// <summary>
        /// Lấy môn học chi tiết với số khóa học
        /// </summary>
        public DataTable GetWithCourseCount(long subjectID)
        {
            if (!bolIsExistIData) objIData = DCore.Data.CreateData();
            try
            {
                objIData.CreateNewStoredProcedure("SIM_Subject_GetWithCourseCount");
                objIData.AddParameter("@SubjectID", subjectID);
                return objIData.ExecStoreToDataTable();
            }
            catch (Exception objEx)
            {
                this.objErrorException = objEx;
                return null;
            }
            finally { if (!bolIsExistIData) objIData.Disconnect(); }
        }

        #endregion
    }
}
